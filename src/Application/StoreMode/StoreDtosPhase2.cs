using Domain.Enums;

namespace Application.StoreMode;

/// <summary>
/// A manager's credentials for an approval at the till. Needed when the cashier lacks the permission for
/// the step (a big discount, a price change, a cancel, a return); the manager is recorded in the approval log.
/// </summary>
public class StoreApprovalRequest
{
    /// <summary>The manager's own staff code (the one they sign in to the POS with).</summary>
    public string? Code { get; set; }

    // Older clients: the manager's username and password.
    public string? UserName { get; set; }
    public string? Password { get; set; }
    public string? Reason { get; set; }
}

// ---- Quick slots ---------------------------------------------------------------------------

public class StoreQuickSlotResponse
{
    public int SlotNumber { get; set; }
    public int? ProductId { get; set; }
    public string? ProductName { get; set; }
    public decimal? SalePrice { get; set; }
    public UnitOfMeasure? Unit { get; set; }
    public string? Label { get; set; }
    public string? Color { get; set; }
}

public class SaveStoreQuickSlotRequest
{
    /// <summary>1 to 50.</summary>
    public int SlotNumber { get; set; }

    /// <summary>Null (or no product) empties the slot.</summary>
    public int? ProductId { get; set; }
    public string? Label { get; set; }
    public string? Color { get; set; }
}

// ---- Held sales ----------------------------------------------------------------------------

public class HoldStoreSaleRequest
{
    public int StoreCashRegisterId { get; set; }
    public string? Title { get; set; }
    public List<HeldCartLine> Lines { get; set; } = new();
}

public class HeldCartLine
{
    public int ProductId { get; set; }
    public decimal Quantity { get; set; }
    public decimal DiscountAmount { get; set; }
    public List<string>? SerialNumbers { get; set; }
}

public class StoreHeldSaleResponse
{
    public int Id { get; set; }
    public string? Title { get; set; }
    public DateTime CreatedAtUtc { get; set; }
    public int ItemCount { get; set; }
    public decimal Total { get; set; }
    public int CashierUserId { get; set; }
    public string? CashierName { get; set; }
    public List<HeldCartLine> Lines { get; set; } = new();
}

// ---- Serial / IMEI -------------------------------------------------------------------------

public class StoreSerialUnitResponse
{
    public int Id { get; set; }
    public string SerialNumber { get; set; } = default!;
    public int ProductId { get; set; }
    public string ProductName { get; set; } = default!;
    public int? WarehouseId { get; set; }
    public string? WarehouseName { get; set; }
    public StoreSerialStatus Status { get; set; }
    public DateTime? SoldAtUtc { get; set; }
    public List<StoreSerialEventResponse> History { get; set; } = new();
}

public class StoreSerialEventResponse
{
    public StoreSerialEventType Type { get; set; }
    public DateTime CreatedAtUtc { get; set; }
    public string? DocumentType { get; set; }
    public string? DocumentNo { get; set; }
    public string? Note { get; set; }
}

// ---- Returns and exchange ------------------------------------------------------------------

public class StoreSaleForReturnResponse
{
    public StoreSaleResponse Sale { get; set; } = default!;
    public List<StoreReturnableLineResponse> Lines { get; set; } = new();
}

public class StoreReturnableLineResponse
{
    public int SaleLineId { get; set; }
    public int ProductId { get; set; }
    public string ProductName { get; set; } = default!;
    public bool TracksSerial { get; set; }
    public decimal SoldQuantity { get; set; }
    public decimal ReturnedQuantity { get; set; }
    public decimal ReturnableQuantity { get; set; }

    /// <summary>What one unit is worth back (the line total after discount divided by its quantity).</summary>
    public decimal UnitAmount { get; set; }

    /// <summary>The serial numbers sold on this line that can still come back.</summary>
    public List<string> SoldSerials { get; set; } = new();
}

public class CreateStoreReturnRequest
{
    /// <summary>Generated by the client; resending the same id never creates a second return.</summary>
    public Guid OperationId { get; set; }

    public int StoreSaleId { get; set; }
    public string Reason { get; set; } = default!;
    public List<CreateStoreReturnLineRequest> Lines { get; set; } = new();

    /// <summary>How the money goes back: Cash or Card.</summary>
    public StorePaymentMethod RefundMethod { get; set; } = StorePaymentMethod.Cash;
    public StoreApprovalRequest? Approval { get; set; }
}

public class CreateStoreReturnLineRequest
{
    public int SaleLineId { get; set; }
    public decimal Quantity { get; set; }
    public StoreReturnCondition Condition { get; set; } = StoreReturnCondition.Sellable;

    /// <summary>For a serial / IMEI product: which units come back (as many as the quantity).</summary>
    public List<string>? SerialNumbers { get; set; }
}

/// <summary>An exchange: goods come back and new goods are sold in one step; the price difference is paid or refunded.</summary>
public class CreateStoreExchangeRequest
{
    public CreateStoreReturnRequest Return { get; set; } = default!;
    public CreateStoreSaleRequest NewSale { get; set; } = default!;
}

public class StoreReturnLineResponse
{
    public int ProductId { get; set; }
    public string ProductName { get; set; } = default!;
    public decimal Quantity { get; set; }
    public decimal Amount { get; set; }
    public StoreReturnCondition Condition { get; set; }
}

public class StoreReturnResponse
{
    public int Id { get; set; }
    public string DocumentNo { get; set; } = default!;
    public DateTime CreatedAtUtc { get; set; }
    public int StoreSaleId { get; set; }
    public string SaleDocumentNo { get; set; } = default!;
    public string? RegisterName { get; set; }
    public string? CashierName { get; set; }
    public string Reason { get; set; } = default!;
    public decimal TotalAmount { get; set; }
    public decimal RefundAmount { get; set; }
    public StorePaymentMethod RefundMethod { get; set; }
    public decimal DebtCreditAmount { get; set; }
    public decimal BonusRefundAmount { get; set; }
    public decimal BonusClawbackAmount { get; set; }
    public int? ExchangeSaleId { get; set; }
    public List<StoreReturnLineResponse> Lines { get; set; } = new();
}

public class StoreExchangeResponse
{
    public StoreReturnResponse Return { get; set; } = default!;
    public StoreSaleResponse Sale { get; set; } = default!;
}
