// Builds lib/search-index.generated.ts: for every sidebar page, the words and phrases written inside it
// (headings, labels, placeholders, descriptions, button texts), so the sidebar search can find a page
// by something that is only mentioned inside it ("Slogan" -> Tənzimləmələr).
//
// Run by hand with `npm run build:search`; it also runs before `dev` and `build`.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const read = (file) => readFileSync(file, "utf8");

function pageFile(href) {
  const file = join(root, "app", href, "page.tsx");
  return existsSync(file) ? file : null;
}

function resolveImport(spec) {
  if (!spec.startsWith("@/")) return null;
  // UI primitives, services and constants hold no page text worth searching, and the shared table
  // chrome ("Next", "Reset filters", ...) is on every page, so it would match everything.
  if (/^@\/(components\/ui|lib\/services|lib\/constants|hooks|contexts|components\/data-table|components\/advanced-table-filters)/.test(spec)) return null;
  const base = join(root, spec.slice(2));
  for (const candidate of [`${base}.tsx`, `${base}.ts`, join(base, "index.tsx")]) {
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

function localImports(source) {
  const out = [];
  for (const m of source.matchAll(/from\s+["'](@\/[^"']+)["']/g)) {
    const file = resolveImport(m[1]);
    if (file) out.push(file);
  }
  return out;
}

function looksLikeText(s) {
  if (s.length < 3 || s.length > 140) return false;
  if (!/\p{L}{2,}/u.test(s)) return false;
  if (/[{}]|=>|;|\bimport\b|\bconst\b|\breturn\b|\.\.\/|https?:|\/api\//.test(s)) return false;
  if (!/^[\p{L}\p{N}"'“«]/u.test(s)) return false; // starts like a sentence, not like code
  if (/\b(Promise|Record|Array|void|string|number|boolean|undefined|null)\b|===|\):/.test(s)) return false;
  if (/^[\w-]+(\s[\w-]+){0,2}$/.test(s) && /^[a-z]/.test(s) && !/[ğüşöçıəĞÜŞÖÇİƏ]/.test(s) && s === s.toLowerCase() && !s.includes(" ")) {
    return false; // a bare lowercase identifier / css token
  }
  return true;
}

function extractTexts(source) {
  const found = new Set();
  const add = (raw) => {
    const text = raw.replace(/\s+/g, " ").replace(/&nbsp;/g, " ").trim();
    if (looksLikeText(text)) found.add(text);
  };

  // JSX text between tags
  for (const m of source.matchAll(/>([^<>{}]{2,200})</g)) add(m[1]);
  // text attributes
  for (const m of source.matchAll(/\b(?:placeholder|label|title|aria-label|description|alt)\s*=\s*"([^"]{2,140})"/g)) add(m[1]);
  // text properties in config objects: label: "…", title: "…"
  for (const m of source.matchAll(/\b(?:label|title|description|placeholder|heading|hint)\s*:\s*["'`]([^"'`\n]{2,140})["'`]/g)) add(m[1]);
  // strings inside JSX expressions: {"…"}
  for (const m of source.matchAll(/\{\s*["']([^"'\n]{3,140})["']\s*\}/g)) add(m[1]);

  return found;
}

function collect(entry) {
  const seen = new Set();
  const texts = new Set();
  const visit = (file, depth) => {
    if (seen.has(file)) return;
    seen.add(file);
    const source = read(file);
    for (const t of extractTexts(source)) texts.add(t);
    if (depth < 2) for (const next of localImports(source)) visit(next, depth + 1);
  };
  visit(entry, 0);
  return [...texts];
}

const constants = read(join(root, "lib", "constants.ts"));
const hrefs = [...new Set([...constants.matchAll(/href:\s*"(\/dashboard[^"]*)"/g)].map((m) => m[1]))];

const index = {};
for (const href of hrefs) {
  const file = pageFile(href);
  if (!file) continue;
  index[href] = collect(file).sort((a, b) => a.localeCompare(b));
}

const body = JSON.stringify(index, null, 2);
const out = `// Generated by scripts/build-search-index.mjs — do not edit by hand. Run \`npm run build:search\`.
// What is written inside each dashboard page, for the sidebar search.
export const PAGE_SEARCH_INDEX: Record<string, string[]> = ${body};
`;
writeFileSync(join(root, "lib", "search-index.generated.ts"), out);

const pages = Object.keys(index).length;
const phrases = Object.values(index).reduce((n, list) => n + list.length, 0);
console.log(`Search index: ${phrases} phrases from ${pages} pages`);
